#!/usr/bin/env python3
"""Write docker-compose.yml from locations/order: one collector per location whose .env file exists.

The first location (home) polls at full rate; the rest are demo cities that poll WX_POLL_SCALE (4x) slower and catch up
when the display switches to them. Run after adding or removing a location.
"""
from __future__ import annotations

import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOC = ROOT / "locations"


# Optional MCP server (read-only tools for LLMs). Runs only with COMPOSE_PROFILES=mcp, which kiosk/setup.sh writes to
# .env when kiosk.conf has MCP=yes. It reaches the collectors on the compose network, not through the host ports.
MCP_SERVICE = [
    "",
    "  mcp:",
    "    build: ./mcp",
    "    image: wxterm-mcp",
    '    profiles: ["mcp"]',
    "    restart: unless-stopped",
    "    mem_limit: 128m",
    "    read_only: true",
    "    cap_drop: [ALL]",
    '    security_opt: ["no-new-privileges:true"]',
    '    group_add: ["${KIOSK_GID:-65534}"]  # the kiosk group, to drop screenshot requests',
    "    environment:",
    '      MCP_TOKEN: "${MCP_TOKEN:-}"',
    '      WXTERM_ONLY: "${WXTERM_ONLY:-}"',
    '    ports: ["${MCP_BIND:-0.0.0.0}:${MCP_PORT:-8090}:8090"]',
    "    volumes:",
    '      - "./locations:/locations:ro"',
    '      - "${STATE_DIR:-/var/lib/wxterm}:/state:ro"',
    '      - "${STATE_DIR:-/var/lib/wxterm}/requests:/state/requests"',
    '      - "/etc/os-release:/host/os-release:ro"',
]


def read_order() -> list[tuple[str, int]]:
    out = []
    for line in (LOC / "order").read_text().splitlines():
        line = line.split("#", 1)[0].split()
        if len(line) == 2:
            out.append((line[0], int(line[1])))
    return out


def only() -> set[str]:
    """WXTERM_ONLY from the environment, else from .env (kiosk.conf LOCATIONS, written by setup.sh). Empty = all."""
    val = os.environ.get("WXTERM_ONLY")
    if val is None:
        try:
            for line in (ROOT / ".env").read_text().splitlines():
                if line.startswith("WXTERM_ONLY="):
                    val = line.split("=", 1)[1].strip().strip('"')
        except OSError:
            pass
    return {n for n in re.split(r"[\s,]+", val or "") if n}


def main():
    keep = only()
    locs = [(n, p) for n, p in read_order() if (LOC / f"{n}.env").exists() and (not keep or n in keep)]
    if not locs:
        raise SystemExit("no locations: add one with scripts/new-location.py")
    out = [
        "# Generated by scripts/gen-compose.py from locations/order. Don't edit by hand.",
        "# One weather collector per location; the display switches between them with `l`.",
        "x-collector: &collector",
        "  build: ./collector",
        "  image: wxterm-collector",
        "  restart: unless-stopped",
        "  mem_limit: 256m",
        "",
        "services:",
    ]
    for i, (n, port) in enumerate(locs):
        scale = "1" if i == 0 else "4"
        out += [
            f"  {n}:",
            "    <<: *collector",
            f"    env_file: locations/{n}.env",
            "    environment:",
            '      WX_UA: "${WX_UA:-}"',
            f'      WX_POLL_SCALE: "{scale}"',
            f'    ports: ["127.0.0.1:{port}:8091"]  # localhost only: the display runs on this machine',
            f'    volumes: ["./locations:/locations:ro", "wx-{n}:/data"]',
        ]
    out += MCP_SERVICE
    out += ["", "volumes:"] + [f"  wx-{n}:" for n, _ in locs]
    (ROOT / "docker-compose.yml").write_text("\n".join(out) + "\n")
    print(f"docker-compose.yml: {', '.join(n for n, _ in locs)}" + (f" (LOCATIONS: {' '.join(sorted(keep))})"
                                                                    if keep else ""))


if __name__ == "__main__":
    main()
